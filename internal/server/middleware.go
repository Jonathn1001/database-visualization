package server

import (
	"context"
	"log/slog"
	"net/http"
	"time"

	"github.com/go-chi/chi/v5/middleware"
)

// Per-route timeouts (§7.3, §15.3).
const (
	introspectTimeout = 60 * time.Second
	queryTimeout      = 30 * time.Second
	explainTimeout    = 10 * time.Second
)

// timeout derives a request context with the given deadline so downstream
// adapter calls abort when it elapses (§15.3).
func timeout(d time.Duration) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			ctx, cancel := context.WithTimeout(r.Context(), d)
			defer cancel()
			next.ServeHTTP(w, r.WithContext(ctx))
		})
	}
}

// queryTimeoutMW applies the standard query timeout.
var queryTimeoutMW = timeout(queryTimeout)

// requestLogger logs each request via slog. Credential redaction happens in the
// slog handler (see internal/obs), so no sensitive data is emitted here.
func requestLogger(log *slog.Logger) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			start := time.Now()
			ww := middleware.NewWrapResponseWriter(w, r.ProtoMajor)
			next.ServeHTTP(ww, r)
			log.Info("request",
				"method", r.Method,
				"path", r.URL.Path,
				"status", ww.Status(),
				"bytes", ww.BytesWritten(),
				"duration_ms", time.Since(start).Milliseconds(),
				"request_id", middleware.GetReqID(r.Context()),
			)
		})
	}
}
